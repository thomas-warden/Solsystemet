"""Deterministic, tileable surface-gradient/mineral map for the imagined belt.

RG: signed surface slopes; B: mineral reflectance; A: crevice occlusion.
Linear data, not a photograph. Mipmaps are generated by the renderer.
"""
from pathlib import Path
import numpy as np
from PIL import Image

SIZE = 1024
rng = np.random.default_rng(4705)
y, x = np.mgrid[0:SIZE, 0:SIZE].astype(np.float32)

def noise(cells):
    grid = rng.random((cells, cells), dtype=np.float32)
    u, v = x / SIZE * cells, y / SIZE * cells
    i, j = u.astype(int), v.astype(int)
    u, v = u - i, v - j
    u, v = u*u*(3-2*u), v*v*(3-2*v)
    return ((grid[j % cells, i % cells]*(1-u) + grid[j % cells, (i+1) % cells]*u)*(1-v)
            + (grid[(j+1) % cells, i % cells]*(1-u) + grid[(j+1) % cells, (i+1) % cells]*u)*v)

broad, patches, grit, fine, dust = [noise(n) for n in (5, 17, 61, 173, 347)]
height = .40*broad + .42*patches + .14*grit + .03*fine + .01*dust

# Sparse, broken fracture edges. Toroidal distance keeps every seam continuous.
nearest = np.full((SIZE, SIZE), 1e8, dtype=np.float32)
second = nearest.copy()
for sx, sy in rng.random((38, 2))*SIZE:
    dx, dy = np.abs(x-sx), np.abs(y-sy)
    distance = np.hypot(np.minimum(dx, SIZE-dx), np.minimum(dy, SIZE-dy))
    second = np.minimum(second, np.maximum(nearest, distance))
    nearest = np.minimum(nearest, distance)
cracks = np.exp(-((second-nearest)/2.6)**2)*np.clip((patches-.34)*3, 0, 1)
height -= cracks*.13

# Small impact pits and their rims; larger crater relief lives in the geometry.
pits = np.zeros_like(height)
for sx, sy, radius in rng.random((90, 3)):
    dx, dy = np.abs(x-sx*SIZE), np.abs(y-sy*SIZE)
    d = np.hypot(np.minimum(dx, SIZE-dx), np.minimum(dy, SIZE-dy))/(3+radius*16)
    bowl = np.maximum(0, 1-d*d)**2
    height += .035*np.exp(-((d-.96)*12)**2)-bowl*.10
    pits += bowl
reflectance = np.clip(.48+(broad-.5)*.34+(patches-.5)*.21+(grit-.5)*.06-cracks*.19-pits*.06, 0, 1)
occlusion = np.clip(1-cracks*.26-pits*.14, 0, 1)
# Prefilter slopes, rather than differentiating height after rasterization.
# Mip levels then converge to a flat normal without triangle-edge sparkle.
slope_u = (np.roll(height, -1, axis=1)-np.roll(height, 1, axis=1))*(SIZE/2)*2.3*.012
slope_v = (np.roll(height, -1, axis=0)-np.roll(height, 1, axis=0))*(SIZE/2)*2.3*.012
pixels = np.stack([np.clip(slope_u, -1, 1)*.5+.5, np.clip(slope_v, -1, 1)*.5+.5, reflectance, occlusion], axis=-1)
destination = Path(__file__).resolve().parents[1]/'assets/rock-material.png'
Image.fromarray(np.round(pixels*255).astype(np.uint8), 'RGBA').save(destination, optimize=True)
print(f'{destination.name}: {destination.stat().st_size:,} bytes')
